/**
 * AquaFlow Fountain Show Exporter
 * Exports fountain layout + choreography to multiple 3D rendering formats:
 *   - Blender Python script (.py) — imports geometry + keyframes automatically
 *   - Alembic-style JSON (.abc.json) — point cache for particle sims
 *   - USD ASCII (.usda) — Universal Scene Description for Lumen/Twinmotion
 *   - FBX-JSON (.fbx.json) — fixture layout for any DCC tool
 *   - CSV timeline (.csv) — per-nozzle intensity over time for any renderer
 */

// ── Physical constants (match simulation) ───────────────────────────────────
const GRAVITY = 9.81;
const AIR_DRAG = 0.018;

// ── Nozzle physics: compute trajectory analytically ─────────────────────────
function computeJetTrajectory(nozzle, intensity, numPoints = 32) {
  const type   = nozzle.type || 'jet_3d';
  const ox     = nozzle.x   || 0;
  const oz     = nozzle.z   || 0;
  const tiltX  = ((nozzle.tiltX || 0) * Math.PI) / 180;
  const tiltZ  = ((nozzle.tiltZ || 0) * Math.PI) / 180;

  // Initial velocity based on nozzle type
  const speedMap = {
    jet_1d:   4.5 + intensity * 5.5,
    jet_2d:   5.5 + intensity * 7.0,
    jet_3d:   6.5 + intensity * 8.5,
    geyser:   9.0 + intensity * 13.0,
    arch:     5.0 + intensity * 6.5,
    laminar:  6.5 + intensity * 7.5,
    ring:     3.5 + intensity * 4.5,
    mist:     0.8 + intensity * 1.8,
    cascade:  0.5 + intensity * 1.5,
  };
  const speed = speedMap[type] || (5.0 + intensity * 6.0);

  let vx, vy, vz;
  if (type === 'arch') {
    const toCenter = Math.atan2(-oz, -ox);
    const archAngle = (28 + intensity * 18) * Math.PI / 180;
    vx = Math.cos(toCenter) * Math.cos(archAngle) * speed;
    vy = Math.sin(archAngle) * speed;
    vz = Math.sin(toCenter) * Math.cos(archAngle) * speed;
  } else {
    vx = Math.sin(tiltX) * speed;
    vy = Math.cos(tiltX) * Math.cos(tiltZ) * speed;
    vz = Math.sin(tiltZ) * speed;
  }

  const points = [];
  const dt = (vy > 0 ? (vy * 2.2 / GRAVITY) : 1.5) / numPoints;

  for (let i = 0; i <= numPoints; i++) {
    const t = i * dt;
    const drag = Math.exp(-AIR_DRAG * t);
    const x = ox + vx * t * drag;
    const y = vy * t - 0.5 * GRAVITY * t * t;
    const z = oz + vz * t * drag;
    if (y < -0.1) break;
    points.push({ x: +x.toFixed(4), y: +Math.max(0, y).toFixed(4), z: +z.toFixed(4) });
  }
  return points;
}

// ── Main export functions ─────────────────────────────────────────────────────

/**
 * Export fountain layout + show as Blender Python script.
 * Run in Blender's scripting editor to auto-build scene + animate.
 */
export function exportToBlender(showData, options = {}) {
  const { tracks = [], currentShow = {}, engineeringFixtures = [] } = showData;
  const poolRadius = options.poolRadius || 6;
  const fps        = options.fps        || 24;
  const duration   = currentShow.duration || 120;
  const totalFrames = Math.ceil(duration * fps);

  // Build nozzle list from engineering fixtures or default layout
  const nozzles = engineeringFixtures.length > 0
    ? engineeringFixtures
    : _defaultNozzleLayout(poolRadius);

  // Compute timeline data per nozzle
  const nozzleTimelines = _computeNozzleTimelines(nozzles, tracks, duration, fps);

  let py = `"""
AquaFlow Fountain Scene — Auto-generated by AquaFlow Studio
Show: ${currentShow.name || 'Untitled'}
BPM: ${currentShow.bpm || 128}  Duration: ${duration}s
Generated: ${new Date().toISOString()}

USAGE:
1. Open Blender (4.0+)
2. Go to Scripting workspace
3. Paste this script and click Run
4. Scene will be built automatically with animated water jet heights
"""

import bpy
import math

# ── Setup ─────────────────────────────────────────────────────────────────────
bpy.ops.object.select_all(action='SELECT')
bpy.ops.object.delete()

scene = bpy.context.scene
scene.frame_start = 1
scene.frame_end   = ${totalFrames}
scene.render.fps  = ${fps}

# ── Materials ─────────────────────────────────────────────────────────────────
def make_water_mat(name="Water", r=0.3, g=0.6, b=0.9, alpha=0.8):
    mat = bpy.data.materials.new(name=name)
    mat.use_nodes = True
    bsdf = mat.node_tree.nodes.get("Principled BSDF")
    bsdf.inputs["Base Color"].default_value = (r, g, b, 1)
    bsdf.inputs["Roughness"].default_value  = 0.05
    bsdf.inputs["IOR"].default_value        = 1.333  # water IOR
    bsdf.inputs["Transmission Weight"].default_value = 0.85
    mat.blend_method = "BLEND"
    return mat

water_mat = make_water_mat()

def make_pool_mat():
    mat = bpy.data.materials.new(name="Pool")
    mat.use_nodes = True
    bsdf = mat.node_tree.nodes.get("Principled BSDF")
    bsdf.inputs["Base Color"].default_value = (0.7, 0.65, 0.55, 1)
    bsdf.inputs["Roughness"].default_value  = 0.4
    bsdf.inputs["Metallic"].default_value   = 0.3
    return mat

pool_mat = make_pool_mat()

# ── Pool geometry ─────────────────────────────────────────────────────────────
bpy.ops.mesh.primitive_cylinder_add(
    vertices=64, radius=${poolRadius}, depth=0.4, location=(0, 0, 0.2))
pool = bpy.context.active_object
pool.name = "Pool_Wall"
pool.data.materials.append(pool_mat)

bpy.ops.mesh.primitive_circle_add(
    fill_type='TRIFAN', vertices=64, radius=${poolRadius - 0.15},
    location=(0, 0, 0.02))
water_surface = bpy.context.active_object
water_surface.name = "Water_Surface"
water_surface.data.materials.append(water_mat)

# ── Nozzles + animated jet cylinders ─────────────────────────────────────────
nozzle_data = [
`;

  // Write nozzle definitions
  nozzles.forEach((nz, i) => {
    const timeline = nozzleTimelines[i] || [];
    const typeStr = nz.type || 'jet_3d';
    const speedMap = {
      jet_1d: [4.5, 5.5], jet_2d: [5.5, 7.0], jet_3d: [6.5, 8.5],
      geyser: [9.0, 13.0], arch: [5.0, 6.5], laminar: [6.5, 7.5],
    };
    const [sBase, sRange] = speedMap[typeStr] || [5.0, 6.0];
    const maxH = ((sBase + sRange) ** 2) / (2 * GRAVITY);

    py += `    {"id": "${nz.id || `nozzle_${i}`}", "x": ${(nz.x||0).toFixed(3)}, `;
    py += `"y": 0, "z": ${(nz.z||0).toFixed(3)}, "type": "${typeStr}", `;
    py += `"max_height": ${maxH.toFixed(2)}},\n`;
  });

  py += `]

nozzle_objects = []
for nd in nozzle_data:
    # Nozzle base marker
    bpy.ops.mesh.primitive_cylinder_add(
        vertices=8, radius=0.06, depth=0.15,
        location=(nd["x"], nd["z"], 0.08))
    base = bpy.context.active_object
    base.name = f"Nozzle_{nd['id']}_Base"
    base.data.materials.append(pool_mat)

    # Water jet cylinder (height animated)
    bpy.ops.mesh.primitive_cylinder_add(
        vertices=12, radius=0.04, depth=1.0,
        location=(nd["x"], nd["z"], 0.5))
    jet = bpy.context.active_object
    jet.name = f"Jet_{nd['id']}"
    jet.data.materials.append(water_mat)
    nozzle_objects.append((jet, nd))

# ── Keyframe animation ────────────────────────────────────────────────────────
timeline_data = {
`;

  // Write per-nozzle keyframes (sample every 10 frames)
  nozzles.forEach((nz, i) => {
    const timeline = nozzleTimelines[i] || [];
    py += `    "${nz.id || `nozzle_${i}`}": [`;
    // Sample every 6 frames
    const keyframes = timeline.filter((_, fi) => fi % 6 === 0);
    py += keyframes.map(kf => `(${kf.frame}, ${kf.intensity.toFixed(3)})`).join(', ');
    py += `],\n`;
  });

  py += `}

for jet, nd in nozzle_objects:
    nid = nd["id"]
    if nid not in timeline_data:
        continue
    for frame, intensity in timeline_data[nid]:
        height = max(0.05, intensity * nd["max_height"])
        bpy.context.scene.frame_set(frame)
        jet.scale.z = height
        jet.location.z = height / 2 + 0.08
        jet.keyframe_insert(data_path="scale",    index=2)
        jet.keyframe_insert(data_path="location", index=2)
        # Opacity
        if jet.data.materials:
            mat = jet.data.materials[0]
            bsdf = mat.node_tree.nodes.get("Principled BSDF")
            if bsdf:
                bsdf.inputs["Alpha"].default_value = 0.2 + intensity * 0.7
                bsdf.inputs["Alpha"].keyframe_insert("default_value", frame=frame)

# ── Lights — point lights with animated RGB color ─────────────────────────────
light_positions = [
    (${poolRadius * 0.6}, ${poolRadius * 0.6}, 0.5),
    (-${poolRadius * 0.6}, ${poolRadius * 0.6}, 0.5),
    (${poolRadius * 0.6}, -${poolRadius * 0.6}, 0.5),
    (-${poolRadius * 0.6}, -${poolRadius * 0.6}, 0.5),
    (0, ${poolRadius * 0.5}, 0.3),
    (0, -${poolRadius * 0.5}, 0.3),
]

for i, pos in enumerate(light_positions):
    bpy.ops.object.light_add(type='POINT', location=pos)
    light = bpy.context.active_object
    light.name = f"FountainLight_{i}"
    light.data.energy = 800
    light.data.color = (0.3, 0.6, 1.0)
    light.data.shadow_soft_size = 0.5

# ── Camera ────────────────────────────────────────────────────────────────────
bpy.ops.object.camera_add(location=(${poolRadius * 2.5}, ${poolRadius * 2.5}, ${poolRadius * 1.5}))
cam = bpy.context.active_object
cam.name = "FountainCamera"
bpy.ops.object.constraint_add(type='TRACK_TO')
cam.constraints["Track To"].target = water_surface
cam.constraints["Track To"].track_axis = 'TRACK_NEGATIVE_Z'
cam.constraints["Track To"].up_axis = 'UP_Y'
scene.camera = cam

# ── HDRI Environment ──────────────────────────────────────────────────────────
world = bpy.data.worlds["World"]
world.use_nodes = True
bg = world.node_tree.nodes.get("Background")
if bg:
    bg.inputs["Color"].default_value = (0.02, 0.04, 0.08, 1)
    bg.inputs["Strength"].default_value = 0.5

print("✓ AquaFlow fountain scene built successfully!")
print(f"  Nozzles: ${nozzles.length}")
print(f"  Duration: ${duration}s @ ${fps}fps = ${totalFrames} frames")
print("  Ready for Cycles/EEVEE rendering")
`;

  return py;
}

/**
 * Export fountain show as USD ASCII format.
 * Compatible with Lumen (Unreal Engine), Twinmotion, Omniverse.
 */
export function exportToUSD(showData, options = {}) {
  const { tracks = [], currentShow = {}, engineeringFixtures = [] } = showData;
  const poolRadius = options.poolRadius || 6;
  const fps        = options.fps        || 24;
  const duration   = currentShow.duration || 120;
  const nozzles    = engineeringFixtures.length > 0
    ? engineeringFixtures : _defaultNozzleLayout(poolRadius);
  const nozzleTimelines = _computeNozzleTimelines(nozzles, tracks, duration, fps);

  let usd = `#usda 1.0
(
    defaultPrim = "FountainShow"
    doc = "AquaFlow Studio Export — ${currentShow.name || 'Fountain Show'}"
    upAxis = "Y"
    metersPerUnit = 1.0
    timeCodesPerSecond = ${fps}
    startTimeCode = 0
    endTimeCode = ${Math.ceil(duration * fps)}
)

def Xform "FountainShow" (
    kind = "assembly"
)
{
    # Pool
    def Mesh "Pool" {
        float3[] extent = [(-${poolRadius + 0.3}, -0.05, -${poolRadius + 0.3}), (${poolRadius + 0.3}, 0.45, ${poolRadius + 0.3})]
        double radius = ${poolRadius}
        double height = 0.4
    }

    # Water Surface
    def Mesh "WaterSurface" {
        float3[] extent = [(-${poolRadius}, 0, -${poolRadius}), (${poolRadius}, 0.02, ${poolRadius})]
        bool doubleSided = 1
    }

    # Nozzles
    def Scope "Nozzles" {
`;

  nozzles.forEach((nz, i) => {
    const id = (nz.id || `nozzle_${i}`).replace(/[^a-zA-Z0-9_]/g, '_');
    const timeline = nozzleTimelines[i] || [];
    const speedMap = { jet_1d: [4.5, 5.5], jet_2d: [5.5, 7.0], jet_3d: [6.5, 8.5], geyser: [9.0, 13.0] };
    const [sBase, sRange] = speedMap[nz.type] || [5.0, 6.0];
    const maxH = ((sBase + sRange) ** 2) / (2 * GRAVITY);

    // Sample keyframes
    const keyframes = timeline.filter((_, fi) => fi % 3 === 0);
    const scaleKeys = keyframes.map(kf => `${kf.frame}: ${Math.max(0.01, kf.intensity * maxH).toFixed(3)}`).join(', ');
    const opacityKeys = keyframes.map(kf => `${kf.frame}: ${(0.2 + kf.intensity * 0.7).toFixed(3)}`).join(', ');

    usd += `
        def Xform "${id}" {
            double3 xformOp:translate = (${(nz.x||0).toFixed(3)}, 0, ${(nz.z||0).toFixed(3)})
            uniform token[] xformOpOrder = ["xformOp:translate"]

            def Mesh "JetMesh" {
                float3[] extent = [(-0.05, 0, -0.05), (0.05, ${maxH.toFixed(2)}, 0.05)]
            }

            double3 xformOp:scale.timeSamples = {${scaleKeys}}

            def Material "WaterMaterial_${id}" {
                float inputs:opacity.timeSamples = {${opacityKeys}}
                color3f inputs:diffuseColor = (0.3, 0.6, 0.95)
                float inputs:roughness = 0.05
                float inputs:ior = 1.333
            }
        }`;
  });

  usd += `
    }

    # Lights
    def Scope "Lights" {`;

  const lightAngles = [0, 60, 120, 180, 240, 300];
  lightAngles.forEach((deg, i) => {
    const rad = deg * Math.PI / 180;
    const lx = Math.cos(rad) * poolRadius * 0.5;
    const lz = Math.sin(rad) * poolRadius * 0.5;
    usd += `
        def SphereLight "PoolLight_${i}" {
            float3 xformOp:translate = (${lx.toFixed(2)}, 0.3, ${lz.toFixed(2)})
            color3f color = (0.3, 0.6, 1.0)
            float intensity = 500
            float radius = 0.1
        }`;
  });

  usd += `
    }
}
`;
  return usd;
}

/**
 * Export per-nozzle intensity CSV — universal format for any renderer.
 * Each row: time_seconds, nozzle_id, intensity (0-1), height_m
 */
export function exportToCSV(showData, options = {}) {
  const { tracks = [], currentShow = {}, engineeringFixtures = [] } = showData;
  const poolRadius  = options.poolRadius  || 6;
  const sampleRate  = options.sampleRate  || 10; // samples per second
  const duration    = currentShow.duration || 120;
  const nozzles     = engineeringFixtures.length > 0
    ? engineeringFixtures : _defaultNozzleLayout(poolRadius);

  const speedMap = {
    jet_1d: [4.5, 5.5], jet_2d: [5.5, 7.0], jet_3d: [6.5, 8.5],
    geyser: [9.0, 13.0], arch: [5.0, 6.5], laminar: [6.5, 7.5],
    ring: [3.5, 4.5], mist: [0.8, 1.8],
  };

  let csv = 'time_s,nozzle_id,nozzle_type,x,z,intensity,height_m,velocity_m_s\n';
  const steps = Math.ceil(duration * sampleRate);

  for (let step = 0; step <= steps; step++) {
    const t = step / sampleRate;
    nozzles.forEach(nz => {
      const intensity = _getIntensityAtTime(nz, tracks, t);
      const [sBase, sRange] = speedMap[nz.type] || [5.0, 6.0];
      const speed  = sBase + intensity * sRange;
      const height = (speed * speed) / (2 * GRAVITY) * intensity;
      csv += `${t.toFixed(2)},${nz.id||'nozzle'},${nz.type||'jet'},${(nz.x||0).toFixed(2)},${(nz.z||0).toFixed(2)},${intensity.toFixed(4)},${height.toFixed(3)},${(speed*intensity).toFixed(3)}\n`;
    });
  }
  return csv;
}

/**
 * Export trajectory point cache — Alembic-compatible JSON.
 * Contains full parabolic arc geometry for each nozzle at each time step.
 * Use in Blender Geometry Nodes, Houdini, or Twinmotion custom assets.
 */
export function exportToAlembicJSON(showData, options = {}) {
  const { tracks = [], currentShow = {}, engineeringFixtures = [] } = showData;
  const poolRadius  = options.poolRadius  || 6;
  const fps         = options.fps         || 24;
  const duration    = currentShow.duration || 120;
  const nozzles     = engineeringFixtures.length > 0
    ? engineeringFixtures : _defaultNozzleLayout(poolRadius);

  const frames = [];
  const sampleEvery = Math.max(1, Math.round(fps / 12)); // max 12fps for file size

  for (let f = 0; f <= Math.ceil(duration * fps); f += sampleEvery) {
    const t = f / fps;
    const frameData = { frame: f, time: +t.toFixed(3), nozzles: [] };

    nozzles.forEach(nz => {
      const intensity = _getIntensityAtTime(nz, tracks, t);
      if (intensity < 0.01) {
        frameData.nozzles.push({ id: nz.id, intensity: 0, points: [] });
        return;
      }
      const points = computeJetTrajectory(nz, intensity, 16);
      frameData.nozzles.push({
        id:        nz.id || 'nozzle',
        type:      nz.type,
        intensity: +intensity.toFixed(4),
        points,
      });
    });
    frames.push(frameData);
  }

  return JSON.stringify({
    format:   'AquaFlowAlembic',
    version:  '1.0',
    show:     currentShow.name || 'Untitled',
    fps,
    duration,
    nozzleCount: nozzles.length,
    frameCount:  frames.length,
    nozzles:  nozzles.map(nz => ({
      id:    nz.id,
      type:  nz.type,
      x:     nz.x, z: nz.z,
      tiltX: nz.tiltX||0, tiltZ: nz.tiltZ||0,
    })),
    frames,
  }, null, 2);
}

// ── Internal helpers ──────────────────────────────────────────────────────────

function _getIntensityAtTime(nozzle, tracks, t) {
  const typeToTrackType = {
    jet_1d:'pump', jet_2d:'pump', jet_3d:'pump', geyser:'pump',
    laminar:'pump', arch:'valve', ring:'valve', cascade:'valve',
    mist:'fog', pirouette:'pump',
  };
  const trackType = typeToTrackType[nozzle.type] || 'pump';
  const relevantTracks = tracks.filter(tr =>
    tr.type === trackType && !tr.muted
  );
  let maxIntensity = 0;
  relevantTracks.forEach(track => {
    const clip = (track.clips || []).find(c =>
      parseFloat(c.start) <= t && t < parseFloat(c.end)
    );
    if (clip) maxIntensity = Math.max(maxIntensity, (clip.intensity || 0) / 100);
  });
  return maxIntensity;
}

function _computeNozzleTimelines(nozzles, tracks, duration, fps) {
  const totalFrames = Math.ceil(duration * fps);
  return nozzles.map(nz => {
    const keyframes = [];
    for (let f = 0; f <= totalFrames; f += 2) { // every 2 frames
      const t = f / fps;
      keyframes.push({ frame: f + 1, intensity: _getIntensityAtTime(nz, tracks, t) });
    }
    return keyframes;
  });
}

function _defaultNozzleLayout(poolRadius) {
  const nozzles = [];
  nozzles.push({ id:'center_geyser', type:'geyser', x:0, z:0, tiltX:0, tiltZ:0 });
  for (let i=0; i<6; i++) {
    const a = (i/6)*Math.PI*2;
    const r = poolRadius * 0.52;
    nozzles.push({ id:`jet_ring_${i}`, type:'jet_3d', x:Math.cos(a)*r, z:Math.sin(a)*r,
      tiltX:Math.sin(a)*12, tiltZ:Math.cos(a)*12 });
  }
  for (let i=0; i<4; i++) {
    const a = (i/4)*Math.PI*2;
    const r = poolRadius * 0.78;
    nozzles.push({ id:`arch_${i}`, type:'arch', x:Math.cos(a)*r, z:Math.sin(a)*r, tiltX:35 });
  }
  for (let i=0; i<4; i++) {
    const a = (i/4)*Math.PI*2;
    const r = poolRadius * 0.35;
    nozzles.push({ id:`laminar_${i}`, type:'laminar', x:Math.cos(a)*r, z:Math.sin(a)*r });
  }
  for (let i=0; i<12; i++) {
    const a = (i/12)*Math.PI*2;
    const r = poolRadius * 0.90;
    nozzles.push({ id:`mist_${i}`, type:'mist', x:Math.cos(a)*r, z:Math.sin(a)*r });
  }
  return nozzles;
}
