// @vitest-environment jsdom
import { afterEach, describe, expect, it, vi } from 'vitest';
import React from 'react';
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { makeSong, SONGS, SITES } from './evalCorpus';
import { siteContext } from './showGenerators';
import { createShow } from './autoShow';
import { compileStudio } from './showModel';
import { measureShow } from './showMetrics';
import { buildSiteModel } from './siteCapability';
import { applyFix, describeForCritic, fixLabel, planPhrases, requestCritique, validateCritique } from './aiCritic';

vi.mock('../../../utils/apiClient', () => ({ apiPost: vi.fn(), apiGet: vi.fn(), apiUrl: (p) => `/api${p}` }));
import { apiPost } from '../../../utils/apiClient';
import PlanStrip from './PlanStrip';

globalThis.IS_REACT_ACT_ENVIRONMENT = true;
globalThis.React = React;

const site = siteContext(SITES.ring().fixtures);
const pop = makeSong(SONGS.pop);
const show = createShow(site.studio, { analysis: pop.analysis, stems: pop.stems, items: site.items, groups: site.groups, design: site.design });
const studio = show.studio, plan = studio.plan;
const phrases = planPhrases(plan);
const [phraseId, areas] = [...phrases].find(([, g]) => g.length >= 1);
const sectionId = phraseId.split(':')[0];

afterEach(() => { cleanup(); vi.mocked(apiPost).mockReset(); });

describe('AI critic — description and request', () => {
  it('sends the measured show, plan ids and looks as text', async () => {
    const { clips } = compileStudio(studio, site.items);
    const measured = measureShow({ clips, items: site.items, analysis: pop.analysis, studio });
    const scm = buildSiteModel(site.items, { design: site.design });
    const text = describeForCritic({ plan, measured, scm, analysis: pop.analysis });
    expect(text).toMatch(/QUALITY: score [\d.]+ \/ 100/);
    expect(text).toContain(`${phraseId} ·`);
    expect(text).toContain('METRICS');
    const post = vi.fn(async () => ({ findings: [] }));
    await requestCritique({ plan, measured, scm, analysis: pop.analysis }, { post });
    const [path, body] = post.mock.calls[0];
    expect(path).toBe('/ai/critique');
    expect(body.sections).toEqual(plan.sections.map((s) => s.id));
    expect(body.phrases.find((p) => p.id === phraseId).groups).toEqual(areas);
    expect(body.groups).toEqual(expect.arrayContaining(areas));
  });
});

describe('AI critic — validating the review', () => {
  it('keeps known ids, turns the rest into advice and sorts by severity', () => {
    const out = validateCritique({ summary: 'ok', findings: [
      { severity: 'low', title: 'Late', detail: '', fix: { kind: 'retime', phraseId, shiftS: 9 } },
      { severity: 'high', title: 'Swap', detail: '', fix: { kind: 'swap-look', phraseId, groupId: 'ghost', look: 'pulse' } },
      { severity: 'medium', title: 'Unknown look', detail: '', fix: { kind: 'swap-look', phraseId, look: 'moonwalk' } },
      { severity: 'medium', title: 'Mute nothing', detail: '', fix: { kind: 'mute', sectionId: 'S99', groupId: areas[0] } },
      { severity: 'severe', title: 'Bad severity', detail: '', fix: null },
      { severity: 'low', title: '', detail: 'no title', fix: null },
    ] }, plan);
    expect(out.findings.map((f) => f.severity)).toEqual(['high', 'medium', 'medium', 'low']);
    expect(out.findings[0].fix).toEqual({ kind: 'swap-look', phraseId, groupId: null, look: 'pulse' });
    expect(out.findings[1].fix).toEqual({ kind: 'none' });
    expect(out.findings[2].fix).toEqual({ kind: 'none' });
    expect(out.findings[3].fix).toEqual({ kind: 'retime', phraseId, shiftS: 4 });
    expect(validateCritique(null, plan).findings).toEqual([]);
    expect(fixLabel({ kind: 'retime', shiftS: -0.5 })).toBe('Earlier by 0.5 s');
  });
});

describe('AI critic — applying fixes', () => {
  const mine = (s) => s.recipes.filter((r) => r.pattern?.plan === plan.id && r.pattern.phrase === phraseId);

  it('swap-look locks the phrase at the new look (regenerated by the plan strip)', () => {
    const out = applyFix(studio, { kind: 'swap-look', phraseId, groupId: null, look: 'pulse' });
    for (const a of areas) expect(out.locks[`${phraseId}:${a}`]).toBe('pulse');
    const again = createShow({ ...studio, plan: { ...plan, locks: out.locks } }, { analysis: pop.analysis, stems: pop.stems, items: site.items, groups: site.groups, design: site.design });
    const s = again.plan.sections.find((x) => x.id === sectionId);
    expect(s.phrases[Number(phraseId.split(':')[1])].voices.every((v) => v.look === 'pulse')).toBe(true);
  });

  it('retime, mute and level edit only that phrase', () => {
    expect(mine(studio).length).toBeGreaterThan(0);
    const later = applyFix(studio, { kind: 'retime', phraseId, shiftS: 0.5 }).studio;
    mine(later).forEach((r, i) => expect(r.start).toBeCloseTo(Math.max(0, mine(studio)[i].start + 0.5), 3));
    const others = (s) => s.recipes.filter((r) => !mine(studio).some((m) => m.id === r.id));
    expect(others(later)).toEqual(others(studio));
    const muted = applyFix(studio, { kind: 'mute', phraseId, groupId: areas[0] }).studio;
    expect(mine(muted).filter((r) => r.pattern.group === areas[0]).every((r) => r.muted)).toBe(true);
    const quiet = applyFix(studio, { kind: 'level', phraseId, groupId: null, level: 40 }).studio;
    const water = mine(quiet).filter((r) => r.pattern.role !== 'lights');
    expect(water.every((r) => (r.effect === 'field' ? r.field.high === 40 : r.intensity === 40))).toBe(true);
    expect(applyFix(studio, { kind: 'mute', sectionId: 'S99', groupId: areas[0] })).toBeNull();
    expect(applyFix(studio, { kind: 'none' })).toBeNull();
  });
});

describe('AI critic — plan strip UI', () => {
  it('asks the engine, lists findings and applies a fix with one change', async () => {
    vi.mocked(apiPost).mockResolvedValue({ summary: 'Strong arc, thin climax.', model: 'claude-opus-5-5', findings: [
      { severity: 'high', title: 'Too loud here', detail: 'Bring it down.', fix: { kind: 'level', phraseId, sectionId: null, groupId: null, look: null, shiftS: null, level: 40 } },
      { severity: 'low', title: 'Add mist', detail: 'More atmosphere.', fix: { kind: 'none' } },
    ] });
    const onChange = vi.fn();
    render(<PlanStrip studio={studio} items={site.items} analysis={pop.analysis} pps={10} onChange={onChange} />);
    fireEvent.click(screen.getByRole('button', { name: '✦ AI critic' }));
    await screen.findByRole('dialog', { name: 'AI critic' });
    expect(vi.mocked(apiPost).mock.calls[0][0]).toBe('/ai/critique');
    expect(screen.getByText('Strong arc, thin climax.')).toBeTruthy();
    expect(screen.getByText('(advice)', { exact: false })).toBeTruthy();
    fireEvent.click(screen.getByRole('button', { name: 'Apply · Level 40 %' }));
    expect(onChange).toHaveBeenCalledTimes(1);
    const next = onChange.mock.calls[0][0](studio);
    expect(mine(next).filter((r) => r.pattern.role !== 'lights').every((r) => (r.effect === 'field' ? r.field.high === 40 : r.intensity === 40))).toBe(true);
    expect(screen.getByRole('button', { name: 'Applied' }).disabled).toBe(true);
  });

  it('shows the route message when the AI fails', async () => {
    vi.mocked(apiPost).mockRejectedValue(new Error('HTTP 502 — AI critic: the API key was not accepted'));
    render(<PlanStrip studio={studio} items={site.items} analysis={pop.analysis} pps={10} onChange={vi.fn()} />);
    fireEvent.click(screen.getByRole('button', { name: '✦ AI critic' }));
    await waitFor(() => expect(screen.getByText('AI critic: the API key was not accepted')).toBeTruthy());
    expect(screen.queryByRole('dialog', { name: 'AI critic' })).toBeNull();
  });

  function mine(s) { return s.recipes.filter((r) => r.pattern?.plan === plan.id && r.pattern.phrase === phraseId); }
});
