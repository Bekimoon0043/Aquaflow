/**
 * fixtureReferenceProducts.js — real-world fountain equipment (manufacturer catalogue data)
 *
 * Products the generic library did not have, or only had as an AquaFlow template:
 * catalogue nozzles (OASE, Safe-Rain, Longxin, Huaxin, Crystal Fountains, Atlantic, LSI,
 * Kasco), DMX swing drives, rotating hydraulic nozzles, air shooters, water screens,
 * digital curtains, fog, fire-water, lights, pumps, valves, show control and accessories.
 *
 * Each entry records ONE catalogue operating point (height · flow · pressure) plus the
 * published range, the source page and a confidence note. Values marked "est." in
 * `referenceNote` are derived, not published. Nothing here is a verified datasheet in the
 * app's provenance sense (no document revision / licence attached), so every entry is
 * still flagged generic — confirm with the supplier before ordering.
 *
 * Hydraulics: `nozzleDiaMm` is the EQUIVALENT orifice that reproduces the catalogue flow
 * at the catalogue pressure (Q = Cd·n·π/4·d²·√(2gH)); the real outlet size, where
 * published, is `outletDiaMm`.
 *
 * `preview3d` picks the 3D renderer type; `resolverKey` picks the runtime channel set
 * (fixtureTypeResolver FIXTURE_TYPE_MAP key). This module imports nothing.
 */

const G = 9.81;
const BAR_TO_M = 10.197;
const MCA = 0.0981; // metres of water column → bar
const r2 = (v) => Math.round(v * 100) / 100;
const r3 = (v) => Math.round(v * 1000) / 1000;

function equivalentOrificeMm(q, p, n, cd) {
  const v = Math.sqrt(2 * G * p * BAR_TO_M);
  return Math.sqrt(q / (cd * n * Math.PI / 4 * v * 60000)) * 1000;
}

/** Water nozzle from one catalogue operating point (h m · q L/min · p bar). */
function nozzle({ key, label, family, maker, model, conn, h, q, p, n = 1, outletDia, cd = 0.93, spray = 0,
  material = "SS304", preview3d, resolverKey, tags, extra = {}, src, note }) {
  return {
    key, category: "Nozzles", family, label, manufacturer: maker, model,
    color: "#3aa8ff", icon: "↑", preview3d, resolverKey,
    ...(tags ? { tags } : {}),
    engineering: {
      flowLpm: r2(q), pressureBar: r3(p), jetHeightM: r2(h),
      nozzleDiaMm: r2(equivalentOrificeMm(q, p, n, cd)), orificeCount: n, dischargeCoeff: cd,
      kFactor: r3(q / Math.sqrt(p)), heightEfficiency: r3(h / (p * BAR_TO_M)),
      connectionSize: conn, sprayAngleDeg: spray, material, group: family,
      ...(outletDia ? { outletDiaMm: outletDia } : {}),
      ...extra,
      referenceSource: src, referenceNote: note,
    },
  };
}

function device({ key, label, category, family, maker, model, icon = "▣", color = "#99aabb", preview3d, resolverKey,
  tags, engineering, src, note }) {
  return {
    key, category, family, label, manufacturer: maker, model, color, icon, preview3d, resolverKey,
    ...(tags ? { tags } : {}),
    engineering: { ...engineering, referenceSource: src, referenceNote: note },
  };
}

function light({ key, label, maker, model, watts, beam, mode, lumens, dmx, extra = {}, src, note }) {
  return device({
    key, label, category: "Lights", family: "Fountain Lights (catalogue)", maker, model, icon: "★", color: "#ffddaa",
    engineering: {
      wattage: watts, voltage: 24, beamAngleDeg: beam, colorMode: mode, dmxChannels: dmx,
      ...(lumens ? { lumens } : {}), ipRating: "IP68", controlProtocol: "DMX512", ...extra,
    },
    src, note,
  });
}

function pump({ key, label, maker, model, kw, q, head, voltage = 230, conn, extra = {}, src, note }) {
  return device({
    key, label, category: "Pumps", family: "Fountain Pumps (catalogue)", maker, model, icon: "⊚", color: "#88aa88",
    engineering: {
      flowLpm: r2(q), flowM3Hr: r3(q * 0.06), headM: head, pressureBar: r3(head / BAR_TO_M), powerKw: kw,
      voltage, connectionSize: conn, group: "Pump", ...extra,
    },
    src, note,
  });
}

