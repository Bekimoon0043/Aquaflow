// Extract every editable Bellagio recipe as a portable pattern asset and as the app's built-in pack.
//   vite-node --root . scripts/extract-bellagio-pattern-assets.mjs <show.aquapkg> [out.aqpattern.json]
import fs from "node:fs";
import path from "node:path";
import { readZip, zipText } from "/src/utils/zipStore.js";
import { readStudio } from "/src/components/programmer/studio/showModel.js";
import { exportPatterns, showBlocks } from "/src/components/programmer/studio/showBlocks.js";

const [srcPath, outPath] = process.argv.slice(2);
if (!srcPath) {
  console.error("usage: vite-node --root . scripts/extract-bellagio-pattern-assets.mjs <show.aquapkg> [out.aqpattern.json]");
  process.exit(1);
}

const zip = readZip(fs.readFileSync(srcPath));
const project = JSON.parse(zipText(zip.get("project.aqua")));
const studio = readStudio(project.programmer || {});
const blocks = showBlocks(studio).filter((b) => !b.background && b.type !== "recorded");
if (!blocks.length) throw new Error("The package has no editable patterns.");
const file = exportPatterns(studio, blocks);
const groups = new Map(studio.groups.map((g) => [g.id, g]));
const fixtures = new Map((project.engineering?.fixtures || []).map((f) => [f.id, f]));

const roleOf = (recipe) => {
  if (recipe.attribute === "motion_angle") return "motion";
  const source = studio.recipes.find((r) => r.id === recipe.id);
  const group = groups.get(source?.groupId || recipe.groupId);
  const members = (group?.memberFixtureIds || []).map((id) => fixtures.get(id)).filter(Boolean);
  if (members.length && members.every((f) => /^light_/.test(f.type))) return "lights";
  return "water";
};

const categoryOf = (pattern, roles) => {
  const name = pattern.name.toLowerCase();
  if (roles.length === 1 && roles[0] === "motion") return "Motion & swings";
  if (roles.length === 1 && roles[0] === "lights") return "Lighting";
  if (/sung|singer|vocal|lyric/.test(name)) return "Lyrics & hits";
  if (/shot|shooter|column|salvo|hit|flash|cannon/.test(name)) return "Shooters & hits";
  if (/draw|rise|ramp|grow|fall|settle|open|close/.test(name)) return "Draw-ons & ramps";
  if (pattern.recipes.some((r) => r.effect === "curve")) return "Curves & dances";
  if (pattern.recipes.every((r) => r.effect === "static")) return "Holds";
  return "Waves & sweeps";
};

file.pack = {
  id: "bellagio-tiesto",
  name: "Bellagio · Tiësto",
  description: "All editable water, light and moving-nozzle patterns from the reconstructed Bellagio show.",
  source: "Bellagio_Tiesto_Real_Layout.aquapkg",
  version: 1,
};
file.patterns = file.patterns.map((pattern, index) => {
  const recipes = pattern.recipes.map((r) => ({ ...r, role: roleOf(r) }));
  const roles = [...new Set(recipes.map((r) => r.role))];
  return {
    ...pattern,
    id: `bellagio-${String(index + 1).padStart(3, "0")}`,
    category: categoryOf(pattern, roles),
    targets: roles,
    recipes,
  };
});

const modulePath = path.resolve("src/assets/patterns/bellagioTiesto.js");
fs.mkdirSync(path.dirname(modulePath), { recursive: true });
fs.writeFileSync(modulePath, `// Generated by scripts/extract-bellagio-pattern-assets.mjs.\nexport default ${JSON.stringify(file, null, 2)};\n`);
const assetPath = path.resolve(outPath || "../../outputs/Bellagio_Tiesto_160_Pattern_Assets.aqpattern.json");
fs.mkdirSync(path.dirname(assetPath), { recursive: true });
fs.writeFileSync(assetPath, `${JSON.stringify(file, null, 2)}\n`);
console.log(`Packaged ${file.patterns.length} patterns`);
console.log(`Built-in pack: ${modulePath}`);
console.log(`Portable pack: ${assetPath}`);
